/* ---------- state helpers ---------- */
const State = {
  KEY: "codequest.v1",
  data: null,

  defaults() {
    return {
      language: null,
      name: "",
      theme: "dark",
      accent: "teal",     // teal | violet | sunset | ocean
      path: null,
      startedAt: null,
      xp: 0,
      completed: {},        // stepId -> true
      seenConcepts: {},     // conceptId -> true
      achievements: {},     // id -> timestamp
      certificates: {},     // pathId -> {id, name, date, skills}
      chatLog: {},          // chatKey -> [ {role, text} ]
      notifications: [],    // {emoji, text, time}
      hintsUsed: {},        // stepId -> count
      dayLog: {},           // 'YYYY-MM-DD' -> count of actions
      lastNotifId: 0
    };
  },

  load() {
    try {
      const raw = localStorage.getItem(this.KEY);
      this.data = raw ? Object.assign(this.defaults(), JSON.parse(raw)) : this.defaults();
    } catch (e) {
      this.data = this.defaults();
    }
    return this.data;
  },

  save() {
    try { localStorage.setItem(this.KEY, JSON.stringify(this.data)); } catch (e) {}
  },

  reset() {
    this.data = this.defaults();
    this.save();
  },

  t(key) {
    const lang = this.data.language === "ar" ? "ar" : "en";
    return I18N[lang][key] !== undefined ? I18N[lang][key] : (I18N.en[key] || key);
  }
};

function t(key) { return State.t(key); }

function applyLanguage() {
  const lang = State.data.language === "ar" ? "ar" : "en";
  document.documentElement.lang = lang;
  document.documentElement.dir = (lang === "ar") ? "rtl" : "ltr";
}

function applyTheme() {
  document.documentElement.dataset.theme = State.data.theme || "dark";
  const ACCENTS = ["teal", "violet", "sunset", "ocean"];
  document.documentElement.dataset.accent = ACCENTS.includes(State.data.accent) ? State.data.accent : "teal";
}

function formatDate(ts) {
  try {
    return new Date(ts).toLocaleDateString(State.data.language === "ar" ? "ar" : "en", { year: "numeric", month: "long", day: "numeric" });
  } catch (e) { return new Date(ts).toDateString(); }
}
